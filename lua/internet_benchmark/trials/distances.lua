local vector1, vector2 = Vector(), Vector()

TRIAL
	:Name("Distance vs DistToSqr")
	:Description("Whether the square root in Distance() is worth paying for when only a comparison (e.g. a nearest-neighbour or range check) is needed, not the actual distance value.")
	:Order(12)
	:Before(function()
		vector1.x = math.random(-1000, 1000)
		vector1.y = math.random(-1000, 1000)
		vector1.z = math.random(-1000, 1000)

		vector2.x = math.random(-1000, 1000)
		vector2.y = math.random(-1000, 1000)
		vector2.z = math.random(-1000, 1000)
	end)
	:Function(function()
		return vector1:Distance(vector2)
	end)
	:Label("Distance")
	:Describe("Includes a square root - only actually necessary when the real distance value is needed, not just its relative size.")
	:Function(function()
		return vector1:DistToSqr(vector2)
	end)
	:Label("DistToSqr")
	:Describe("Skips the square root entirely; fine whenever only relative distance matters, since squaring preserves ordering.")
	:ManualPredefine(1, 1)
	:Exclude("vector1")
	:Exclude("vector2")
