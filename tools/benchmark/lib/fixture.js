const CONTROL = new RegExp("[\\u0000-\\u001f\\u007f]", "g");

/** Quote a string as a Lua literal. */
export function luaString(value) {
	const escaped = String(value)
		.replace(/\\/g, "\\\\")
		.replace(/"/g, "\\\"")
		.replace(/\n/g, "\\n")
		.replace(/\r/g, "\\r")
		// Zero-padded, so an escape followed by a digit cannot swallow it.
		.replace(CONTROL, (char) => `\\${String(char.charCodeAt(0)).padStart(3, "0")}`);

	return `"${escaped}"`;
}

/** Render a list of strings as a Lua table constructor. */
export function luaList(values) {
	if (values.length === 0) {
		return "{}";
	}

	return `{${values.map(luaString).join(", ")}}`;
}

/**
 * Render the config the in-game fixture includes.
 * @param {object} options As returned by parseOptions.
 * @returns {string} Lua source returning a config table.
 */
export function renderConfig(options) {
	return [
		"--- Generated by tools/benchmark/harness.js. Do not edit.",
		"",
		"return {",
		`\ttrial = ${options.trial ? luaString(options.trial) : "nil"},`,
		`\tincludeTags = ${luaList(options.includeTags)},`,
		`\texcludeTags = ${luaList(options.excludeTags)},`,
		`\tdynamic = ${options.dynamic},`,
		`\ttest = ${options.test},`,
		`\twarmup = ${options.warmup},`,
		`\tdeadline = ${options.deadline},`,
		`\tsummary = ${luaString(options.summary)}`,
		"}",
		""
	].join("\n");
}

/**
 * Render the server config appended to the test server's own.
 * GLuaTest's image runs its suite on boot; this run wants the server to itself.
 * @param {object} options As returned by parseOptions.
 * @returns {string}
 */
export function renderServerConfig(options) {
	return [
		"gluatest_server_enable 0",
		"gluatest_client_enable 0",
		`internet_benchmark_logging_level ${options.loggingLevel}`,
		""
	].join("\n");
}
