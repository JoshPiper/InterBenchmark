import assert from "node:assert/strict";
import test from "node:test";
import { luaList, luaString, renderConfig, renderServerConfig } from "../lib/fixture.js";
import { parseOptions } from "../lib/options.js";

test("luaString quotes and escapes", () => {
	assert.equal(luaString("modulo"), "\"modulo\"");
	assert.equal(luaString("say \"hi\""), "\"say \\\"hi\\\"\"");
	assert.equal(luaString("back\\slash"), "\"back\\\\slash\"");
	assert.equal(luaString("two\nlines"), "\"two\\nlines\"");
});

test("luaString zero-pads control escapes so a following digit stays a digit", () => {
	const bell = String.fromCharCode(7);
	assert.equal(luaString(`a${bell}1`), "\"a\\0071\"");
});

test("luaList renders an empty table for no values", () => {
	assert.equal(luaList([]), "{}");
	assert.equal(luaList(["default", "slow"]), "{\"default\", \"slow\"}");
});

test("renderConfig carries a single trial through", () => {
	const config = renderConfig(parseOptions(["--mode=trial", "--trial=modulo", "--iterations=test", "--warmup=3"]));

	assert.match(config, /trial = "modulo",/);
	assert.match(config, /includeTags = \{\},/);
	assert.match(config, /dynamic = false,/);
	assert.match(config, /test = true,/);
	assert.match(config, /warmup = 3,/);
	assert.match(config, /summary = "mode=trial trial=modulo iterations=test"/);
});

test("renderConfig leaves the trial nil for a filtered run", () => {
	const config = renderConfig(parseOptions(["--mode=tag", "--tag=default", "--skip-tag=slow"]));

	assert.match(config, /trial = nil,/);
	assert.match(config, /includeTags = \{"default"\},/);
	assert.match(config, /excludeTags = \{"slow"\},/);
});

test("renderConfig is a Lua chunk returning a table", () => {
	const config = renderConfig(parseOptions([]));

	assert.match(config, /^--- Generated by/);
	assert.match(config, /return \{/);
	assert.ok(config.endsWith("}\n"));
});

test("renderServerConfig keeps GLuaTest's suite out of the way", () => {
	const cfg = renderServerConfig(parseOptions(["--logging-level=10"]));

	assert.match(cfg, /^gluatest_server_enable 0$/m);
	assert.match(cfg, /^gluatest_client_enable 0$/m);
	assert.match(cfg, /^internet_benchmark_logging_level 10$/m);
});
